-- Function to check if a user is an admin
create or replace function is_admin(user_id uuid)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  return exists (
    select 1
    from admin_users
    where admin_users.phone_number = (select raw_user_meta_data->>'phone' from auth.users where id = user_id)
  );
end;
$$;


